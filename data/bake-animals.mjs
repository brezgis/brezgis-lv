// Inline the animal models the scene uses (assets-src/animals/*.glb) as base64
// so the single-file artifact stays offline. Licences and authors are listed in
// assets-src/animals/SOURCES.md and in the Chronicle's credits.
import { readFileSync, writeFileSync } from 'fs';
const USED = [
  'deer_stag', 'deer_doe', 'cattle_bull', 'cattle_cow', 'horse', 'wolf', 'fox', 'pig', 'sheep', 'boar_rigged',
  'hare', 'beaver', 'otter', 'squirrel', 'stork_white', 'heron', 'duck_mallard', 'goose', 'hen', 'rooster',
  'quail_ptarmigan', 'swan_standin', 'frog',
];
let out = '// Generated by data/bake-animals.mjs from assets-src/animals (see SOURCES.md there for authors and licences).\nexport const ANIMAL_GLB = {\n';
let total = 0;
for (const name of USED) {
  const b = readFileSync(new URL(`../assets-src/animals/${name}.glb`, import.meta.url));
  total += b.length;
  out += `  ${name}: "${b.toString('base64')}",\n`;
}
out += '};\n';
writeFileSync(new URL('../src/animal-assets.js', import.meta.url), out);
console.log(`wrote src/animal-assets.js: ${USED.length} models, ${(total / 1024).toFixed(0)} kB`);
